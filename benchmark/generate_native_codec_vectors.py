#!/usr/bin/env python3
"""Generate cross-format logical fixtures from the vendored Python oracle.

These fixtures are not the historical SVG/PNG golden files. They freeze the
intermediate byte streams produced by the current reference implementation so
that the native codec can be expanded without silently changing the protocol.
"""

from __future__ import annotations

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_SRC = ROOT / "server/python/vendor/radialcode/src"
sys.path.insert(0, str(REFERENCE_SRC))

from radialcode.constants import Alphabet, EccLevel, PayloadType  # noqa: E402
from radialcode.encoder import encode  # noqa: E402

OUTPUT = ROOT / "benchmark/fixtures/native_codec_formats_1_5.json"

CASES = (
    ("format1_url_small", 1, 1, b"https://orbiqo.dev/legacy", PayloadType.URL, EccLevel.BALANCED, "none"),
    ("format2_utf8_medium", 2, 2, "Compatibilidade histórica".encode("utf-8"), PayloadType.UTF8, EccLevel.BALANCED, "none"),
    ("format3_binary_large", 3, 3, bytes(range(64)), PayloadType.BINARY, EccLevel.BALANCED, "none"),
    ("format4_binary_micro2", 4, 0, b"f4", PayloadType.BINARY, EccLevel.FAST, "none"),
    ("format4_url_micro4", 4, 5, b"https://orbiqo.dev/f4", PayloadType.URL, EccLevel.BALANCED, "none"),
    ("format5_binary_micro1", 5, 6, b"f5", PayloadType.BINARY, EccLevel.FAST, "none"),
)


def pack_color4(symbols: tuple[int, ...]) -> str:
    packed = bytearray()
    for offset in range(0, len(symbols), 4):
        value = 0
        for symbol in symbols[offset : offset + 4]:
            value = (value << 2) | int(symbol)
        value <<= 2 * (4 - len(symbols[offset : offset + 4]))
        packed.append(value)
    return packed.hex()


def case_record(name: str, format_version: int, geometry_version: int, payload: bytes, payload_type: PayloadType, ecc_level: EccLevel, compression: str) -> dict[str, object]:
    symbol = encode(
        payload,
        geometry=geometry_version,
        alphabet=Alphabet.COLOR4,
        ecc_level=ecc_level,
        palette_id=0,
        payload_type=payload_type,
        compression=compression,
        format_version=format_version,
    )
    return {
        "name": name,
        "format_version": format_version,
        "geometry_version": geometry_version,
        "payload_hex": payload.hex(),
        "payload_type": payload_type.name,
        "ecc_level": ecc_level.name,
        "compression": compression.upper(),
        "palette_id": 0,
        "frame_hex": symbol.frame.encoded_bytes.hex(),
        "rs_concatenated_hex": symbol.rs_encoded.hex(),
        "rs_interleaved_hex": symbol.interleaved.hex(),
        "channel_symbols_packed_hex": pack_color4(symbol.channel.symbols),
        "channel_symbol_count": len(symbol.channel.symbols),
        "mask_id": symbol.channel.mask_id,
        "header_data_hex": f"{symbol.header.to_data_int():012x}",
        "header_codeword_hex": f"{symbol.header.encode_codeword():016x}",
    }


def main() -> int:
    records = [case_record(*case) for case in CASES]
    OUTPUT.write_text(
        json.dumps(
            {
                "specification": "Cross-format logical parity generated by RadialCode reference 0.1.0a6",
                "historical_assets": "not included; original SVG/PNG golden files are unavailable in this tree",
                "vectors": records,
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT} ({len(records)} vectors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
